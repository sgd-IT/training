package com.training.day07;

/**
 * Day 7 - 教科书：一个"什么都不重写"的类（对照用，别改它）
 *
 * 这个类故意**不重写** Object 的任何方法。
 * 它存在的唯一目的：让你亲眼看到"不重写会怎样"。
 *
 * ─────────────────────────────────────────────────────────
 * Java 给每个类白送了三个方法，默认行为是这样的：
 * ─────────────────────────────────────────────────────────
 *
 *   1. toString()
 *      返回 "类名@十六进制hashCode"，例如 com.training.day07.RawPoint@1b6d3586
 *      → 对人不友好，但这就是默认值
 *
 *   2. equals(Object o)
 *      内部就是 this == o，也就是**比地址**
 *      → 两个内容一模一样的 RawPoint，equals 结果是 false ！
 *
 *   3. hashCode()
 *      返回一个由对象地址派生的整数
 *      → 两个内容一模一样的 RawPoint，hashCode 一定不同
 *
 * ─────────────────────────────────────────────────────────
 * 为什么这很危险？
 * ─────────────────────────────────────────────────────────
 *
 * 去看 RawPointTest —— 里面的测试**全部通过**，因为它们记录的正是"默认行为"：
 *   - 放进 HashSet，内容相同的对象**去不掉重**
 *   - 用作 HashMap 的 key，**取不出**你刚存进去的值
 *
 * 而且最坑的是：**编译器一句话都不会说，运行时也不报错，只是结果不对。**
 * （回忆 Day 6：这就是"静默错误"——和 Shape.area() 返回 0 是同一类问题）
 *
 * ─────────────────────────────────────────────────────────
 * 结论
 * ─────────────────────────────────────────────────────────
 *
 * 只要你的类需要"按内容比较"，就必须重写 equals 和 hashCode。
 * 而且**必须成对重写**——只写一个等于没写。
 *
 * 为什么？写 Point 的时候你会亲眼看到。
 */
public class RawPoint {

    private final int x;
    private final int y;

    public RawPoint(int x, int y) {
        this.x = x;
        this.y = y;
    }

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }
}